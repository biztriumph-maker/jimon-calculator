const priceMap = (row: Row): PriceMap => ({
  0: row[4],
  10: row[5],
  20: row[6],
  30: row[7],
  40: row[8],
  50: null,
  60: null,
})

const makeProducts = (type: ProductType, rows: Row[]): Product[] =>
  rows.map((row) => ({
    id: row[0],
    type,
    direction: row[1],
    nameRu: row[2],
    nameZh: row[3],
    image:
      row[0] === 'single-01'
        ? t01Image
        : (singleProductImages[row[0]] ?? complexProductImages[row[0]] ?? null),
    prices: priceMap(row),
  }))

